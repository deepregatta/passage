import { createElement } from 'react';
import { cleanup, render, screen, waitFor } from '@testing-library/react';
import { afterEach, expect, it } from 'vitest';
import BulletinPanel, { isEnglishBulletin } from '../src/components/BulletinPanel.jsx';
import { LocalizedDocument } from '../src/i18n.js';
import { useApp } from '../src/stores/appStore.js';

const initialState = useApp.getState();
afterEach(() => { cleanup(); useApp.setState(initialState, true); });

const ENGLISH = 'SYNTHETIC BULLETIN — Gale warning: W or SW gale force 8 expected later. Generated by the Passage scenario harness; never use for a real passage decision.';
const FRENCH = 'Avis de grand frais à coup de vent. Vent d’ouest 6 à 7, fraîchissant 8 en fin de période. Mer agitée à forte.';
const evidence = { evidence_id: 'E1', source_kind: 'warning', bulletin_ref: { issued_at: '2026-07-20T06:00:00Z', valid_from: '2026-07-20T12:00:00Z', valid_to: '2026-07-21T12:00:00Z', zone_ids: [] } };

function show(language, rawText) {
  useApp.setState({ language, warnings: { source: { mode: 'fixture' }, bulletins: [{ raw_text: rawText, zone_id: 'casquets', kind: 'BMS-large', valid_from: '2026-07-20T12:00:00Z' }] } });
  return render(<div id="root"><BulletinPanel evidence={evidence} onClose={() => {}} />{createElement(LocalizedDocument, { language })}</div>);
}

it('recognises English and French bulletin text', () => {
  expect(isEnglishBulletin(ENGLISH)).toBe(true);
  expect(isEnglishBulletin('Southwest 5 to 7, occasionally gale 8 later. Moderate or rough. Rain then showers. Good, occasionally poor.')).toBe(true);
  expect(isEnglishBulletin(FRENCH)).toBe(false);
});

it('explains in French that an English bulletin is shown in its original language', async () => {
  show('fr', ENGLISH);
  await waitFor(() => expect(screen.getByText('Texte original (en anglais)')).toBeVisible());
  expect(screen.getByRole('dialog').querySelector('pre').textContent).toBe(ENGLISH);
});

it('shows no language note in English or for a French bulletin', () => {
  show('en', ENGLISH);
  expect(screen.queryByText('Original text (in English)')).toBeNull();
  cleanup();
  show('fr', FRENCH);
  expect(screen.queryByText('Texte original (en anglais)')).toBeNull();
  expect(screen.queryByText('Original text (in English)')).toBeNull();
});
