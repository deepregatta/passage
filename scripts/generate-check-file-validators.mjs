#!/usr/bin/env node
// Precompiled JSON Schema validators for the files of a check file (import,
// 2026-11-15). The site's Content-Security-Policy has no 'unsafe-eval', so the
// browser cannot run Ajv's compiler: this script compiles the contracts with
// Ajv's standalone code generation into one plain ES module that the viewer
// imports, with Ajv's single runtime helper and the date-time format inlined
// (no Ajv in the bundle, no eval).
//
//   node scripts/generate-check-file-validators.mjs           write the module
//   node scripts/generate-check-file-validators.mjs --check   fail when it is stale
//
// The module is committed, like the generated briefing message schemas: a
// build never needs Ajv, and `npm test` fails when a contract changes without
// the module being regenerated.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const repo = fileURLToPath(new URL('..', import.meta.url));
// Ajv is the engine's dev dependency (its contract tests use it).
const require = createRequire(`${repo}engine/package.json`);
const Ajv2020 = require('ajv/dist/2020.js').default;
const standalone = require('ajv/dist/standalone/index.js').default;
const { _ } = require('ajv');
const ajvVersion = require('ajv/package.json').version;

const out = `${repo}viewer/src/lib/generated/checkFileValidators.js`;

// Each file of a check and its contract. decision-inputs.json has none: its
// hash is its proof (engine/src/checkFile.ts). synoptic.json is the prepared
// synoptic features document the check used.
export const CHECK_FILE_CONTRACTS = {
  'snapshot.json': 'snapshot.schema.json',
  'findings.json': 'findings.schema.json',
  'briefing.json': 'briefing-reader.schema.json',
  'route.json': 'route.schema.json',
  'plume.json': 'plume.schema.json',
  'warnings.json': 'warnings.schema.json',
  'synoptic.json': 'synoptic-features.schema.json',
  'tides.json': 'tides.schema.json',
};

/**
 * Documented tolerances: where a check file is read more loosely than the
 * contract, and why. The contracts themselves are unchanged.
 *
 * synoptic.json — `route_transitions` is required by the contract, and the
 * Python preparation has always written it (`[]`), but the engine's scenario
 * synoptics and every committed v2 check lack it, and no renderer reads it.
 * The file is tied to the decision hash (canonically the decision inputs'
 * synoptic), so its contract check is for render safety only: it may be absent.
 */
function tolerate(file, schema) {
  if (file === 'synoptic.json') schema.required = schema.required.filter((key) => key !== 'route_transitions');
}

const exportName = (file) => file.replace(/\.json$/, '').replace(/-(\w)/g, (_m, c) => c.toUpperCase());

export function generate() {
  const ajv = new Ajv2020({
    strict: false,
    allErrors: false,
    code: { source: true, esm: true, optimize: true, formats: _`checkFileFormats` },
    // the code refers to checkFileFormats (below) for the format; this placeholder is never run
    formats: { 'date-time': { validate: () => true } },
  });
  for (const [file, contract] of Object.entries(CHECK_FILE_CONTRACTS)) {
    const schema = JSON.parse(readFileSync(`${repo}contracts/${contract}`, 'utf8'));
    tolerate(file, schema);
    ajv.addSchema(schema, exportName(file));
  }
  let code = standalone(ajv, Object.fromEntries(Object.keys(CHECK_FILE_CONTRACTS).map((file) => [exportName(file), exportName(file)])));
  const helper = 'require("ajv/dist/runtime/ucs2length").default';
  if (/require\(/.test(code.replaceAll(helper, ''))) throw new Error('The validators need an Ajv runtime helper this script does not inline.');
  code = code.replaceAll(helper, 'ucs2length').replace(/^"use strict";/, '');
  return `// Generated by scripts/generate-check-file-validators.mjs from contracts/ with Ajv ${ajvVersion}
// standalone code. Do not edit: run \`npm run generate:validators\`; \`npm test\` fails when stale.
// Ajv's runtime helper ucs2length (ajv/dist/runtime/ucs2length), inlined: string
// length in code points, as JSON Schema counts it.
function ucs2length(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  let value;
  while (pos < len) {
    length++;
    value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      value = str.charCodeAt(pos);
      if ((value & 0xfc00) === 0xdc00) pos++;
    }
  }
  return length;
}
// Vendored from ajv-formats 3.0.1 dist/formats.js (full "date-time", strict time
// zone), 2026-11-15; viewer/test/checkFileValidators.test.js compares it with ajv-formats.
const DATE = /^(\\d\\d\\d\\d)-(\\d\\d)-(\\d\\d)$/;
const DAYS = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
const TIME = /^(\\d\\d):(\\d\\d):(\\d\\d(?:\\.\\d+)?)(z|([+-])(\\d\\d)(?::?(\\d\\d))?)?$/i;
const isLeapYear = (year) => year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0);
function fullDate(str) {
  const matches = DATE.exec(str);
  if (!matches) return false;
  const year = +matches[1];
  const month = +matches[2];
  const day = +matches[3];
  return month >= 1 && month <= 12 && day >= 1 && day <= (month === 2 && isLeapYear(year) ? 29 : DAYS[month]);
}
function fullTime(str) {
  const matches = TIME.exec(str);
  if (!matches) return false;
  const hr = +matches[1];
  const min = +matches[2];
  const sec = +matches[3];
  const tz = matches[4];
  const tzSign = matches[5] === '-' ? -1 : 1;
  const tzH = +(matches[6] || 0);
  const tzM = +(matches[7] || 0);
  if (tzH > 23 || tzM > 59 || !tz) return false;
  if (hr <= 23 && min <= 59 && sec < 60) return true;
  const utcMin = min - tzM * tzSign;
  const utcHr = hr - tzH * tzSign - (utcMin < 0 ? 1 : 0);
  return (utcHr === 23 || utcHr === -1) && (utcMin === 59 || utcMin === -1) && sec < 61;
}
export function dateTime(str) {
  const parts = str.split(/t|\\s/i);
  return parts.length === 2 && fullDate(parts[0]) && fullTime(parts[1]);
}
const checkFileFormats = { 'date-time': { validate: dateTime } };
${code}
/** The validator of each file of a check, by file name. */
export const checkFileValidators = {
${Object.keys(CHECK_FILE_CONTRACTS).map((file) => `  ${JSON.stringify(file)}: ${exportName(file)},`).join('\n')}
};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const content = generate();
  if (process.argv.includes('--check')) {
    let current = null;
    try { current = readFileSync(out, 'utf8'); } catch { /* missing */ }
    if (current !== content) {
      console.error(`${out.slice(repo.length)} is stale: run npm run generate:validators.`);
      process.exit(1);
    }
    console.log('check-file validators: up to date');
  } else {
    writeFileSync(out, content);
    console.log(`wrote ${out.slice(repo.length)}`);
  }
}
